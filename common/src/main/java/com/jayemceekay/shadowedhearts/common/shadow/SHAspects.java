package com.jayemceekay.shadowedhearts.common.shadow;

/**
 * String constants for Cobblemon Aspect keys used by this mod.
 */
public final class SHAspects {
    /** Aspect key that marks a Pokemon as a shadow. */
    public static final String SHADOW = "shadowedhearts:shadow"; // string key in Pokemon Aspects
    /** Aspect key that marks a Pokemon currently in Hyper Mode (persists outside battle until cleared). */
    public static final String HYPER_MODE = "shadowedhearts:hyper_mode";
    /** Aspect key that marks a Pokemon currently in Reverse Mode (persists outside battle until cleared). */
    public static final String REVERSE_MODE = "shadowedhearts:reverse_mode";

    /** Explicitly selects the mod's signature Shadow aura presentation. */
    public static final String AURA_STYLE_SIGNATURE = "shadowedhearts:aura_style_signature";
    /** Explicitly selects the Pokemon Colosseum-inspired Shadow aura presentation. */
    public static final String AURA_STYLE_COLOSSEUM = "shadowedhearts:aura_style_colosseum";
    /** Explicitly selects the Pokemon XD-inspired Shadow aura presentation. */
    public static final String AURA_STYLE_XD = "shadowedhearts:aura_style_xd";
    // If you want a family: "sh_shadow_minor", etc.
}
